export function lang() { return chrome.i18n.getUILanguage().toLowerCase().startsWith('pt') ? 'pt-PT' : 'en'; }
export function t(key) { return messages[key]?.[lang() === 'pt-PT' ? 1 : 0] ?? key; }
export function explain(e) { return e?.code === 'httpError' ? `${t('httpError')} ${e.status}.` : t(Object.hasOwn(messages, e?.code) ? e.code : 'unknown'); }
export function applyI18n() {
  document.documentElement.lang = lang();
  for (const n of document.querySelectorAll('[data-i]')) n.textContent = t(n.dataset.i);
  for (const n of document.querySelectorAll('[data-label]')) { n.setAttribute('aria-label', t(n.dataset.label)); n.title = t(n.dataset.label); }
}
