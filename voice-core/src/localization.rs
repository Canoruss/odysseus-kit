#[no_mangle]
pub extern "system" fn Java_com_canorus_odysseus_L_english(mut env: JNIEnv, _: JClass, text: JString) -> jstring {
    let Ok(value) = env.get_string(&text) else { return text.into_raw() };
    let value: String = value.into();
    match english(&value) {
        Some(translated) => env.new_string(translated).map(|s| s.into_raw()).unwrap_or(std::ptr::null_mut()),
        None => text.into_raw(),
    }
}

